import { createHash } from "node:crypto";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname } from "node:path";
import { format } from "oxfmt";

export async function generateMigrations(check = false) {
  const directory = new URL("../../../drizzle/", import.meta.url);
  const journal = JSON.parse(readFileSync(new URL("meta/_journal.json", directory), "utf8"));
  if (
    journal.dialect !== "sqlite" ||
    !Array.isArray(journal.entries) ||
    journal.entries.length === 0
  )
    throw new Error("Expected a nonempty SQLite migration journal");
  const seen = new Set();
  let previousWhen = -1;
  const records = journal.entries.map((entry, index) => {
    if (
      entry.idx !== index ||
      !Number.isSafeInteger(entry.when) ||
      entry.when <= previousWhen ||
      typeof entry.version !== "string" ||
      typeof entry.breakpoints !== "boolean" ||
      typeof entry.tag !== "string" ||
      !/^[A-Za-z0-9_-]+$/.test(entry.tag) ||
      seen.has(entry.tag)
    )
      throw new Error(`Invalid migration journal entry at index ${index}`);
    seen.add(entry.tag);
    previousWhen = entry.when;
    const sql = readFileSync(new URL(`${entry.tag}.sql`, directory), "utf8");
    return {
      id: entry.tag,
      tag: entry.tag,
      idx: entry.idx,
      version: entry.version,
      when: entry.when,
      breakpoints: entry.breakpoints,
      sql,
      hash: createHash("sha256").update(sql).digest("hex"),
    };
  });
  const output = fileURLToPath(new URL("../src/generated/migrations.ts", import.meta.url));
  const source = `// Generated by packages/core/scripts/generate-migrations.mjs. Do not edit.
import type { MigrationRecord } from "../migration-types.js";
const records = ${JSON.stringify(records, null, 2)};
export const migrations: readonly MigrationRecord[] = Object.freeze(records.map(record => Object.freeze({ ...record, statements: Object.freeze(record.sql.split("--> statement-breakpoint")) })));
export const schemaVersion: string = migrations[migrations.length - 1].id;
`;
  const result = await format(output, source, {});
  if (result.errors.length) throw new Error(JSON.stringify(result.errors));
  if (check) {
    if (readFileSync(output, "utf8") !== result.code)
      throw new Error("Bundled migrations are stale. Run pnpm build:core.");
  } else {
    mkdirSync(dirname(output), { recursive: true });
    writeFileSync(output, result.code);
  }
}
if (process.argv[1] === fileURLToPath(import.meta.url))
  await generateMigrations(process.argv.includes("--check"));
