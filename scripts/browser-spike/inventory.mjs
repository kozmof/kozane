import { readdir, readFile, writeFile } from "node:fs/promises";
import { execFileSync } from "node:child_process";

async function files(directory) {
  const entries = await readdir(directory, { withFileTypes: true });
  return (
    await Promise.all(
      entries.map((entry) => {
        const path = `${directory}/${entry.name}`;
        return entry.isDirectory() ? files(path) : path;
      }),
    )
  ).flat();
}
const sources = (await files("src")).filter(
  (path) => /\.(ts|svelte)$/.test(path) && !/\.test\.ts$/.test(path),
);
const sections = [
  [
    "Route and loader database boundaries",
    /src\/routes\/.*\+(server|page\.server|layout\.server)\.ts$/,
    /locals|\bdb\b|withTx|withReadTx|transaction|taskspace|health/,
  ],
  [
    "CLI database and transaction boundaries",
    /src\/cli\/commands\/.*\.ts$/,
    /\bdb\b|withTx|withReadTx|transaction/,
  ],
  [
    "Client transport and environment dependencies",
    /src\/lib\/|src\/routes\/.*\.svelte$/,
    /fetch|\/api\/|\$app\/|KOZANE_SSG|sessionStorage|localStorage|window\.|document\./,
  ],
];
let output = `# Separation source inventory\n\nGenerated by \`node scripts/browser-spike/inventory.mjs\`.\n\nBaseline revision \`${execFileSync("git", ["rev-parse", "HEAD"], { encoding: "utf8" }).trim()}\`.\n\nMatches identify review candidates. Classification and compatibility verification remain pending.\n`;
for (const [title, paths, pattern] of sections) {
  output += `\n## ${title}\n\n`;
  for (const path of sources.filter((path) => paths.test(path)).sort()) {
    const lines = (await readFile(path, "utf8")).split("\n");
    const matches = lines.flatMap((line, index) => (pattern.test(line) ? [`${index + 1}`] : []));
    if (matches.length) output += `- \`${path}\` lines ${matches.join(", ")}\n`;
  }
}
await writeFile("docs/backend-separation/source-inventory.md", output);

const domainCommands = new Set([
  "card",
  "inventory",
  "layer",
  "namespace",
  "partition",
  "scope",
  "tag",
  "warp",
]);
let audit =
  "\n## Adapter classification\n\nClassification describes the adapter's responsibility. Transaction signals identify review candidates and do not prove complete service delegation.\n\n| Adapter | Class | Transaction signal |\n| --- | --- | --- |\n";
for (const path of sources
  .filter(
    (path) =>
      /src\/routes\/.*\+(server|page\.server)\.ts$/.test(path) ||
      /src\/cli\/commands\/.*\.ts$/.test(path),
  )
  .sort()) {
  const source = await readFile(path, "utf8");
  let classification;
  if (path.startsWith("src/routes/")) {
    classification = path.includes("/health/")
      ? "infrastructure"
      : /\/(login|taskspaces)\//.test(path)
        ? "Node feature"
        : "core-backed";
  } else {
    const command = path.slice("src/cli/commands/".length).split(/[/.]/)[0];
    classification = domainCommands.has(command)
      ? "core-backed"
      : ["init", "db", "open", "status"].includes(command)
        ? "infrastructure"
        : "Node feature";
  }
  const transaction = /composeWrite/.test(source)
    ? "core composition"
    : /withTx|\.transaction\(/.test(source)
      ? "adapter transaction, review required"
      : /services\//.test(source)
        ? "delegated service calls"
        : "no explicit transaction, review required";
  audit += `| \`${path}\` | ${classification} | ${transaction} |\n`;
}
await writeFile("docs/backend-separation/source-inventory.md", output + audit);
