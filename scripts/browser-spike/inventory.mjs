import { readdir, readFile, writeFile } from "node:fs/promises";
import { execFileSync } from "node:child_process";
import { auditAdapters } from "../adapter-audit.mjs";

async function files(directory) {
  const entries = await readdir(directory, { withFileTypes: true });
  return (
    await Promise.all(
      entries.map((entry) => {
        const path = `${directory}/${entry.name}`;
        return entry.isDirectory() ? files(path) : path;
      }),
    )
  ).flat();
}
const sources = (
  await Promise.all(["packages/kozane/src", "packages/client/src", "packages/core/src"].map(files))
)
  .flat()
  .filter((path) => /\.(ts|svelte)$/.test(path) && !/\.test\.ts$/.test(path));
let output = `# Separation source inventory\n\nGenerated by \`node scripts/browser-spike/inventory.mjs\`.\n\nInventory base revision \`${execFileSync("git", ["rev-parse", "HEAD"], { encoding: "utf8" }).trim()}\`. Pre-extraction baseline revision \`226facea14e7a9323e4fd6fd1c8d5f4daed76d06\`. The earlier c31206a inventory revision is already part of extraction and is not the performance baseline.\n\nSee [the P0/P1 audit](p0-p1-audit.md) for reviewed responsibilities, compatibility evidence and remaining browser/account checks.\n\n## Adapter classification\n\nThe audit rejects direct domain SQL writes and local write transactions in core-backed frontends. CLI read projections resolve identifiers and format output. Domain validation and mutations belong to public core services.\n\n| Adapter | Class | Responsibility |\n| --- | --- | --- |\n`;
for (const item of auditAdapters())
  output += `| \`${item.path}\` | ${item.classification} | ${item.responsibility} |\n`;
output +=
  "\n## Client transport and environment matches\n\nThese matches distinguish transport/lifecycle adapters from shared views. Shared view transport bans are enforced by lint and standalone browser compilation.\n\n";
for (const path of sources.filter((path) => path.startsWith("packages/client/src/")).sort()) {
  const lines = (await readFile(path, "utf8")).split("\n");
  const matches = lines.flatMap((line, index) =>
    /fetch|\/api\/|\$app\/|KOZANE_SSG|sessionStorage|localStorage|window\.|document\./.test(line)
      ? [index + 1]
      : [],
  );
  if (matches.length) output += `- \`${path}\` lines ${matches.join(", ")}\n`;
}
await writeFile("docs/backend-separation/source-inventory.md", output);
